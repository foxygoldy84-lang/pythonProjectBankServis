from src.services import investment_bank, process_bank_search


def test_investment_bank_calculation():
    """Тест: правильность округления сумм в инвесткопилке по формату ТЗ."""
    test_transactions = [
        {"Дата операции": "01.12.2021", "Сумма операции": -1712.0},  # Округление до 1750 (+38)
        {"Дата операции": "05.12.2021", "Сумма операции": -50.0},    # Округление ровное (+0)
        {"Дата операции": "01.11.2021", "Сумма операции": -100.0},   # Другой месяц (игнорируется)
        {"Дата операции": "10.12.2021", "Сумма операции": 500.0},    # Доход (игнорируется)
    ]
    saved = investment_bank("2021-12", test_transactions, limit=50)
    assert saved == 38.0



def test_process_bank_search():
    """Тест: регистронезависимый поиск по описанию и категории."""
    test_transactions = [
        {"Описание": "Покупка в Супермаркете", "Категория": "Одежда"},
        {"Описание": "Такси", "Категория": "Транспорт"},
        {"Описание": "Аптека", "Категория": "супермаркеты"},
    ]

    results = process_bank_search(test_transactions, "супермаркет")
    assert len(results) == 2
